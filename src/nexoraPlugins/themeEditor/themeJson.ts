export function validateTheme(raw: unknown): { ok: true; theme: NexoraThemeJson; } | { ok: false; error: string; } {
    if (!raw || typeof raw !== "object") return { ok: false, error: "Theme must be a JSON object" };
    const t = raw as NexoraThemeJson;
    if (t.schemaVersion !== 1) return { ok: false, error: "Unsupported schemaVersion (expected 1)" };
    if (!t.name || typeof t.name !== "string") return { ok: false, error: "name is required" };
    if (t.customCss != null && typeof t.customCss !== "string") return { ok: false, error: "customCss must be a string" };
    if (typeof t.customCss === "string" && /<\/?script/i.test(t.customCss)) {
        return { ok: false, error: "customCss must not contain script tags" };
    }
    return { ok: true, theme: { ...DEFAULT_THEME, ...t, colors: { ...DEFAULT_THEME.colors, ...t.colors }, typography: { ...DEFAULT_THEME.typography, ...t.typography }, layout: { ...DEFAULT_THEME.layout, ...t.layout }, effects: { ...DEFAULT_THEME.effects, ...t.effects } } };
}

export function themeToCss(theme: NexoraThemeJson): string {
    const c = theme.colors || {};
    const typo = theme.typography || {};
    const layout = theme.layout || {};
    const effects = theme.effects || {};
    const densityPad = layout.density === "compact" ? "2px" : layout.density === "comfortable" ? "8px" : "4px";

    const lines = [
        "/* Generated by Nexora Theme Editor — CSS only, no JS */",
        ":root {",
        c.accent ? `  --nx-accent: ${c.accent};` : "",
        c.background ? `  --nx-bg: ${c.background};` : "",
        c.chatBackground ? `  --nx-chat-bg: ${c.chatBackground};` : "",
        c.sidebar ? `  --nx-sidebar: ${c.sidebar};` : "",
        c.text ? `  --nx-text: ${c.text};` : "",
        c.textMuted ? `  --nx-text-muted: ${c.textMuted};` : "",
        typo.fontFamily ? `  --nx-font: ${typo.fontFamily};` : "",
        typo.fontSizePx != null ? `  --nx-font-size: ${typo.fontSizePx}px;` : "",
        layout.radiusPx != null ? `  --nx-radius: ${layout.radiusPx}px;` : "",
        layout.avatarSizePx != null ? `  --nx-avatar: ${layout.avatarSizePx}px;` : "",
        `  --nx-msg-pad: ${layout.messageSpacingPx != null ? layout.messageSpacingPx + "px" : densityPad};`,
        effects.transparency != null ? `  --nx-opacity: ${effects.transparency};` : "",
        "}",
        "body {",
        typo.fontFamily ? "  font-family: var(--nx-font) !important;" : "",
        typo.fontSizePx != null ? "  font-size: var(--nx-font-size) !important;" : "",
        c.text ? "  color: var(--nx-text);" : "",
        "}",
        c.background ? "[class*=\"app_\"] { background: var(--nx-bg) !important; }" : "",
        c.chatBackground ? "[class*=\"chat_\"] { background: var(--nx-chat-bg) !important; }" : "",
        c.sidebar ? "[class*=\"sidebar_\"] { background: var(--nx-sidebar) !important; }" : "",
        c.accent ? "[class*=\"lookFilled_\"][class*=\"colorBrand_\"] { background-color: var(--nx-accent) !important; }" : "",
        "[class*=\"message_\"] { padding-top: var(--nx-msg-pad); padding-bottom: var(--nx-msg-pad); }",
        effects.backgroundImageUrl
            ? `body::before { content:""; position:fixed; inset:0; z-index:-1; background:url(${JSON.stringify(effects.backgroundImageUrl)}) center/cover no-repeat; opacity: calc(var(--nx-opacity, 1) * 0.35); pointer-events:none; }`
            : "",
        effects.reducedMotion ? "*, *::before, *::after { animation: none !important; transition: none !important; }" : "",
        theme.customCss ? `\n/* customCss (opt-in) */\n${theme.customCss}` : ""
    ];
    return lines.filter(Boolean).join("\n");
}
