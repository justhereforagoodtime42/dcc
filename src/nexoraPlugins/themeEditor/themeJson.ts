export interface NexoraThemeJson {
    schemaVersion: 1;
    name: string;
    author?: string;
    description?: string;
    colors?: {
        accent?: string;
        background?: string;
        chatBackground?: string;
        sidebar?: string;
        text?: string;
        textMuted?: string;
    };
    typography?: {
        fontFamily?: string;
        fontSizePx?: number;
        fontWeight?: number;
    };
    layout?: {
        messageSpacingPx?: number;
        density?: "comfortable" | "cozy" | "compact";
        radiusPx?: number;
        avatarSizePx?: number;
    };
    effects?: {
        transparency?: number;
        backgroundImageUrl?: string;
        reducedMotion?: boolean;
    };
    /** Opt-in arbitrary CSS — never execute JS */
    customCss?: string;
}

