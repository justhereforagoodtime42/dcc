/*
 * Embed default theme CSS into a TS module so standalone HTTP updates
 * (which only download patcher.js) still ship new themes.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { join, resolve } from "path";

const defaultsSrc = resolve("src/main/themes/defaults");
const outFile = resolve("src/main/themes/bundledThemeSources.generated.ts");

const themes = {};
if (existsSync(defaultsSrc)) {
    for (const name of readdirSync(defaultsSrc)) {
        if (!name.endsWith(".css")) continue;
        themes[name] = readFileSync(join(defaultsSrc, name), "utf-8");
    }
}

const body = `/* AUTO-GENERATED by scripts/build/bundleDefaultThemes.mjs — do not edit */
export const BUNDLED_THEME_CSS: Record<string, string> = ${JSON.stringify(themes, null, 4)};
`;

mkdirSync(resolve("src/main/themes"), { recursive: true });
writeFileSync(outFile, body, "utf-8");
console.log(`Bundled ${Object.keys(themes).length} default themes → ${outFile}`);
